"""One command: run every evaluation, write evaluation/results/{metrics.json,cases.md}.

  python scripts/run_all_evals.py --inprocess        # no servers needed
  python scripts/run_all_evals.py                    # against running servers (ports 8030 / 9025)
"""
import argparse, json
from _common import Api, add_common_args, results_dir
import eval_answer_f1 as A, eval_retrieval as R, eval_risk_agreement as K


def r2(d):
    return {k: (round(v, 3) if isinstance(v, float) else v) for k, v in d.items()}


def main():
    ap = add_common_args(argparse.ArgumentParser())
    a = ap.parse_args()
    api = Api(a.inprocess)
    m = {"retrieval": {}, "qa": {}}
    for sp in ("all", "dev", "test", "blind"):
        ro, _ = R.run(api, sp)
        m["retrieval"][sp] = {"n": ro["n"], "baseline": r2(ro["baseline"]), "app": r2(ro["app"])}
        qo, _ = A.run(api, sp)
        m["qa"][sp] = r2(qo)
    qo, _ = A.run(api, "all", parse_only=True)
    m["qa"]["parse_only_all"] = r2(qo)
    ko, kper = K.run(api)
    m["risk"] = r2(ko)
    m["risk_sweep"] = {n: r2(K.run(api, n)[0]) for n in (3, 4, 5)}
    if a.inprocess:
        import compare_baseline
        m["starter_kit_baseline"] = compare_baseline.run()
    json.dump(m, open(f"{results_dir()}/metrics.json", "w"), indent=2)

    # ---- good / weak cases
    _, qper = A.run(api, "all")
    ans = [p for p in qper if p["expect"]]
    good = sorted([p for p in ans if p["f1"] >= 0.75], key=lambda p: -p["f1"])[:5]
    weak = sorted([p for p in ans if p["f1"] < 0.5], key=lambda p: p["f1"])[:5]
    lines = ["# Logged examples (auto-generated by scripts/run_all_evals.py)\n", "## Q&A - good\n"]
    for p in good:
        lines.append(f"- **{p['question']}** ({p['split']})\n  - answer: {p['answer']}\n  - F1 {p['f1']:.2f}, confidence {p['confidence']}\n")
    lines.append("\n## Q&A - weak\n")
    for p in weak:
        lines.append(f"- **{p['question']}** ({p['split']})\n  - answer: {p['answer']}\n  - reference: {p['reference']}\n  - F1 {p['f1']:.2f}, confidence {p['confidence']}\n")
    lines.append("\n## Risk summaries - best / worst topic-F1\n")
    for p in sorted(kper, key=lambda p: -p["f1"])[:2] + sorted(kper, key=lambda p: p["f1"])[:3]:
        lines.append(f"- **{p['filing_id']}** topic-F1 {p['f1']:.2f}; gold {p['gold']}\n  - bullets: " + " | ".join(p["summary"]) + "\n")
    open(f"{results_dir()}/cases.md", "w", encoding="utf-8").write("\n".join(lines))
    print(json.dumps(m, indent=2))


if __name__ == "__main__":
    main()
